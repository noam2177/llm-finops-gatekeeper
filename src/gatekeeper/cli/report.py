"""Console, JSON/CSV and Markdown renderings of a benchmark run."""

from __future__ import annotations

import csv
import json
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path

from gatekeeper.metrics import CostSummary, EvaluationSummary, PricingModel, Verdict
from gatekeeper.metrics.cost_calculator import render_finops_table
from gatekeeper.pipeline import ExtractionResult

SCENARIO_NAMES: dict[str, str] = {
    "A": "Senior role or scrape noise, blocked by CPU gate",
    "B": "Eligible posting, solved by local model",
    "C": "Local model fails validation, escalated, solved by cloud",
    "D": "Unrecoverable scrape, abstains after escalation",
}


@dataclass(frozen=True, slots=True)
class BenchmarkRun:
    mode: str
    results: list[ExtractionResult]
    verdicts: list[Verdict]
    evaluation: EvaluationSummary
    cost: CostSummary
    pricing: PricingModel


def _table(headers: list[str], rows: list[list[str]]) -> str:
    widths = [max(len(h), *(len(r[i]) for r in rows)) for i, h in enumerate(headers)]

    def line(cells: list[str]) -> str:
        return "| " + " | ".join(c.ljust(w) for c, w in zip(cells, widths, strict=True)) + " |"

    sep = "|" + "|".join("-" * (w + 2) for w in widths) + "|"
    return "\n".join([line(headers), sep, *(line(r) for r in rows)])


def _per_file_rows(run: BenchmarkRun) -> list[list[str]]:
    by_name = {v.filename: v for v in run.verdicts}
    rows = []
    for r in run.results:
        verdict = by_name.get(r.filename)
        rows.append(
            [
                r.filename,
                verdict.scenario if verdict else "-",
                r.status.value,
                r.resolved_by.value if r.resolved_by else "none",
                str(r.local_calls),
                str(r.cloud_calls),
                str(r.total_tokens),
                verdict.verdict if verdict else "unscored",
            ]
        )
    return rows


def _scenario_rows(run: BenchmarkRun) -> list[list[str]]:
    return [
        [key, SCENARIO_NAMES.get(key, "?"), str(b["total"]), f"{b['correct']}/{b['total']}"]
        for key, b in run.evaluation.by_scenario.items()
    ]


def _quality_lines(e: EvaluationSummary) -> list[str]:
    return [
        f"Accuracy vs ground truth: {e.correct}/{e.total} ({e.accuracy_pct}%)",
        f"Hallucinations accepted into output: {e.hallucinations}",
        f"Unexpected routing: {e.wrong_route}",
    ]


def render_console_report(run: BenchmarkRun) -> str:
    per_file = _table(
        ["File", "Scn", "Status", "Resolved", "Local", "Cloud", "Tokens", "Verdict"],
        _per_file_rows(run),
    )
    scenarios = _table(["Scn", "Scenario", "Docs", "Correct"], _scenario_rows(run))
    parts = [
        f"LLM FinOps Gatekeeper benchmark: {run.mode}",
        "",
        per_file,
        "",
        scenarios,
        "",
        *_quality_lines(run.evaluation),
        "",
        "FinOps ROI",
        render_finops_table(run.cost, run.pricing),
    ]
    return "\n".join(parts)


def render_benchmark_markdown(run: BenchmarkRun) -> str:
    stamp = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    quality = "\n".join(f"- {line}" for line in _quality_lines(run.evaluation))
    return f"""# Benchmark results

Generated by `python -m gatekeeper benchmark --dry-run --markdown-out docs/benchmark_results.md`
on {stamp}. Mode: **{run.mode}**.

Dry-run mode uses `MockLLMProvider`, a deterministic simulation of local and
cloud model behaviour, so these numbers are reproducible on any machine. They
demonstrate the routing and the cost model, not the accuracy of a specific LLM.

## FinOps ROI

{render_finops_table(run.cost, run.pricing)}

## Quality

{quality}

## Scenarios

{_table(["Scn", "Scenario", "Docs", "Correct"], _scenario_rows(run))}

## Per-document results

{
        _table(
            ["File", "Scn", "Status", "Resolved", "Local", "Cloud", "Tokens", "Verdict"],
            _per_file_rows(run),
        )
    }
"""


def write_artifacts(run: BenchmarkRun, output_dir: Path) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    summary = {
        "generated_utc": datetime.now(UTC).isoformat(),
        "mode": run.mode,
        "cost": run.cost.to_dict(),
        "evaluation": {
            "total": run.evaluation.total,
            "correct": run.evaluation.correct,
            "wrong_route": run.evaluation.wrong_route,
            "hallucinations": run.evaluation.hallucinations,
            "accuracy_pct": run.evaluation.accuracy_pct,
            "by_scenario": run.evaluation.by_scenario,
        },
    }
    (output_dir / "benchmark_summary.json").write_text(json.dumps(summary, indent=2), "utf-8")
    with (output_dir / "results.csv").open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(
            [
                "filename",
                "scenario",
                "status",
                "resolved_by",
                "local_calls",
                "cloud_calls",
                "tokens",
                "verdict",
            ]
        )
        writer.writerows(_per_file_rows(run))
